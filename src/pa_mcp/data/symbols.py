_cache: Optional[dict] = None


def _load_from_db(symbol: str) -> Optional[str]:
    """从 stock_basic 表查名称。"""
    global _cache
    try:
        from pa_mcp.config import get_settings
        from pa_mcp.data.store import DuckDBStore

        store = DuckDBStore(get_settings().database.path)
        store.connect()
        df = store.query_df(
            "SELECT name FROM stock_basic WHERE symbol = ?", [symbol],
        )
        store.close()
        if not df.empty and df.iloc[0]["name"]:
            return str(df.iloc[0]["name"])
    except Exception:
        pass
    return None


def get_stock_name(symbol: str) -> str:
    """获取股票名称：DB → 内置字典 → '未知'。"""
    symbol = symbol.strip()
    # 去掉前缀（sh/sz/bj）
    if symbol[:2].lower() in ("sh", "sz", "bj"):
        symbol = symbol[2:]

    name = _load_from_db(symbol)
    if name:
        return name
    return COMMON_NAMES.get(symbol, f"{symbol}(未知)")


def with_names(symbols: list[str]) -> dict[str, str]:
    """批量：{symbol: name}"""
    return {s: get_stock_name(s) for s in symbols}
